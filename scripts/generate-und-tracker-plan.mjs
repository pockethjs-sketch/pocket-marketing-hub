import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDir, "..");
const defaultSource = "C:\\Users\\PK-INVEXT\\Downloads\\UND_90일_팀트래커.html";
const sourcePath = path.resolve(process.argv[2] || defaultSource);
const outputPath = path.join(repositoryRoot, "apps-script", "UndTrackerPlan.gs");

const html = fs.readFileSync(sourcePath, "utf8");
const match = html.match(/var\s+TASKS\s*=\s*(\[[\s\S]*?\]);\s*\n/);
if (!match) throw new Error(`TASKS 배열을 찾지 못했습니다: ${sourcePath}`);

const tasks = vm.runInNewContext(`(${match[1]})`, Object.create(null), { timeout: 1000 });
if (!Array.isArray(tasks) || tasks.length !== 144) {
  throw new Error(`예상한 144건과 다릅니다: ${Array.isArray(tasks) ? tasks.length : "not-array"}`);
}

const seen = new Set();
const normalized = tasks.map((task, index) => {
  const item = {
    id: String(task.id || "").trim(),
    team: String(task.team || "").trim(),
    phase: String(task.phase || "").trim(),
    title: String(task.t || "").trim(),
    category: String(task.b || "").trim(),
    week: Number(task.w || 0),
    planNote: String(task.r || "").trim(),
    sortOrder: index + 1,
  };
  if (!item.id || seen.has(item.id)) throw new Error(`중복 또는 빈 업무 ID: ${item.id}`);
  if (!/^(P0|M[123])$/.test(item.phase)) throw new Error(`잘못된 단계: ${item.id}`);
  if (!["MKT", "DSN", "VID"].includes(item.team)) throw new Error(`잘못된 분야: ${item.id}`);
  if (!item.title || !item.category || !Number.isFinite(item.week) || item.week < 1) {
    throw new Error(`필수값 누락: ${item.id}`);
  }
  seen.add(item.id);
  return item;
});

const counts = normalized.reduce(
  (acc, task) => {
    acc.phases[task.phase] = (acc.phases[task.phase] || 0) + 1;
    acc.teams[task.team] = (acc.teams[task.team] || 0) + 1;
    if (task.planNote) acc.contractLinked += 1;
    return acc;
  },
  { phases: {}, teams: {}, contractLinked: 0 },
);

const expected = {
  phases: { P0: 57, M1: 31, M2: 28, M3: 28 },
  teams: { MKT: 79, DSN: 35, VID: 30 },
  contractLinked: 47,
};
if (JSON.stringify(counts) !== JSON.stringify(expected)) {
  throw new Error(`업무 분포 검증 실패: ${JSON.stringify(counts)}`);
}

const banner = [
  "/**",
  " * Generated from the approved UND 90-day tracker.",
  ` * Source: ${path.basename(sourcePath)}`,
  " * Do not edit this file by hand; run scripts/generate-und-tracker-plan.mjs.",
  " */",
].join("\n");
const output = `${banner}\nvar MH_UND_TRACKER_PLAN = ${JSON.stringify(normalized, null, 2)};\n`;
fs.writeFileSync(outputPath, output, "utf8");
console.log(JSON.stringify({ outputPath, tasks: normalized.length, ...counts }, null, 2));
